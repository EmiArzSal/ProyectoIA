// What the interviewer says, and how it is split into audio clips.
//
// Every interviewer message is built by code from fixed parts:
//   intro:    [greeting]               + [question 1]
//   middle:   [ack]                    + [transition?] + [next question]
//   closing:  [ack]                    + [closing]
// Only the ack (one sentence about the last answer) depends on the answer.
// The greeting and the closing are fixed, so they are pre-recorded files; the
// next question is known in advance, so the browser fetches its audio while
// the candidate is still answering. After an answer only the short ack has to
// be generated, which keeps the silence between turns short.
//
// Pure: no DB, network or server-only imports (tested in
// interviewer-script.test.ts, used by the server and the call UI).

import { TECH_QUESTIONS, TOTAL_QUESTIONS } from "./constants";

type Interviewer = { id: string; interviewerName: string; role: string };

export const BEHAVIORAL_TRANSITION = "Now I'd like to ask you some behavioral questions.";
export const CLOSING_TEXT = "That was the last question. Thank you for your time today, and good luck!";

export function introText(agent: Pick<Interviewer, "interviewerName" | "role">): string {
  return (
    `Hi, I'm ${agent.interviewerName}, and I'll be your interviewer for this ${agent.role} position. ` +
    `I'll ask you ${TECH_QUESTIONS} technical questions and then ${TOTAL_QUESTIONS - TECH_QUESTIONS} behavioral questions. ` +
    "Let's begin."
  );
}

/** What is spoken for plan question `index` (0-based), including the transition before the first behavioral one. */
export function questionSpeech(question: string, index: number): string {
  return index === TECH_QUESTIONS ? `${BEHAVIORAL_TRANSITION} ${question}` : question;
}

export type Clip =
  | { kind: "intro" }
  | { kind: "ack" }
  | { kind: "question"; index: number }
  | { kind: "closing" };

/** A clip and the words it says (the call UI highlights them as they are spoken). */
export type SpokenClip = Clip & { text: string };

/**
 * The clips of the interviewer's message after `answered` answers, in
 * playback order. `ack` is ignored for the intro.
 */
export function messageClips(
  answered: number,
  agent: Pick<Interviewer, "interviewerName" | "role">,
  questions: string[],
  ack: string,
): SpokenClip[] {
  if (answered === 0) {
    return [
      { kind: "intro", text: introText(agent) },
      { kind: "question", index: 0, text: questionSpeech(questions[0], 0) },
    ];
  }
  if (answered >= TOTAL_QUESTIONS) {
    return [{ kind: "ack", text: ack }, { kind: "closing", text: CLOSING_TEXT }];
  }
  return [
    { kind: "ack", text: ack },
    { kind: "question", index: answered, text: questionSpeech(questions[answered], answered) },
  ];
}

/** The clips' texts joined: exactly the message stored in the transcript. */
export const joinClips = (clips: Pick<SpokenClip, "text">[]) => clips.map((c) => c.text).join(" ");

/** The interviewer's message after `answered` answers, as stored in the transcript. */
export function composeMessage(
  answered: number,
  agent: Pick<Interviewer, "interviewerName" | "role">,
  questions: string[],
  ack: string,
): string {
  return joinClips(messageClips(answered, agent, questions, ack));
}

/**
 * The fixed tail of the message composed after `answered` answers, i.e.
 * everything after the ack. The intro has no ack, so it has no tail.
 */
function messageTail(answered: number, questions: string[]): string | null {
  if (answered === 0) return null;
  if (answered >= TOTAL_QUESTIONS) return CLOSING_TEXT;
  const question = questions[answered];
  return question === undefined ? null : questionSpeech(question, answered);
}

/**
 * Recovers the ack from a stored message. Returns null when the message does
 * not have the expected shape (e.g. an interview from an older version), so
 * the caller can speak the whole message instead.
 */
export function ackFromMessage(message: string, answered: number, questions: string[]): string | null {
  const tail = messageTail(answered, questions);
  if (!tail || !message.endsWith(` ${tail}`)) return null;
  const ack = message.slice(0, -(tail.length + 1)).trim();
  return ack || null;
}

/**
 * Whether the audio of plan question `index` may be generated now. Only the
 * question being asked and the next one: enough to prefetch while the
 * candidate answers, without generating the whole plan up front.
 */
export function canSpeakQuestion(index: number, userTurns: number): boolean {
  return Number.isInteger(index) && index >= 0 && index < TOTAL_QUESTIONS && index <= userTurns + 1;
}

